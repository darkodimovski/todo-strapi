#!/usr/bin/env bash
# Creates the production .env on the server with freshly generated secrets.
# Secrets are written straight to the file and never printed.
#
#   bash scripts/init-env.sh
set -euo pipefail
cd "$(dirname "$0")/.."

if [ -f .env ]; then
  echo ".env already exists – not overwriting it. Delete it first if you really want new secrets."
  exit 1
fi

rand() { openssl rand -base64 32 | tr -d '\n'; }

read -rp "API domain (e.g. bo-todo-api.duckdns.org): " API_DOMAIN
read -rp "Frontend URL (e.g. https://bo-todo.netlify.app): " FRONTEND_URL
read -rp "Contact e-mail for push (VAPID subject): " CONTACT_EMAIL
read -rp "Gmail address for sending mails (empty = no e-mails): " EMAIL_USER
EMAIL_PASS=""
if [ -n "$EMAIL_USER" ]; then
  read -rsp "Gmail app password (input hidden): " EMAIL_PASS
  echo
fi

echo "Generating VAPID keys for push notifications…"
VAPID_JSON=$(docker run --rm node:20-bookworm-slim npx -y web-push@3.6.7 generate-vapid-keys --json)
VAPID_PUBLIC=$(echo "$VAPID_JSON" | sed -E 's/.*"publicKey":"([^"]+)".*/\1/')
VAPID_PRIVATE=$(echo "$VAPID_JSON" | sed -E 's/.*"privateKey":"([^"]+)".*/\1/')

umask 077
cat > .env <<EOF
# --- generated by scripts/init-env.sh on $(date -I) ---
API_DOMAIN=${API_DOMAIN}
PUBLIC_URL=https://${API_DOMAIN}
CORS_ORIGINS=${FRONTEND_URL%/}
FRONTEND_URL=${FRONTEND_URL%/}

APP_KEYS=$(rand),$(rand),$(rand),$(rand)
API_TOKEN_SALT=$(rand)
ADMIN_JWT_SECRET=$(rand)
TRANSFER_TOKEN_SALT=$(rand)
JWT_SECRET=$(rand)

VAPID_PUBLIC_KEY=${VAPID_PUBLIC}
VAPID_PRIVATE_KEY=${VAPID_PRIVATE}
VAPID_SUBJECT=mailto:${CONTACT_EMAIL}

EMAIL_USER=${EMAIL_USER}
EMAIL_PASS=${EMAIL_PASS}
EOF
chmod 600 .env

echo ".env created (permissions 600). Secrets were not printed."
echo "Note: everyone has to log in again on the new server (new JWT secret)."
